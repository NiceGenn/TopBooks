test('edits survive reload; notes, backup export and validated import work', async ({ page }) => {
  await page.getByRole('button', { name: 'Маленький принц', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Статус чтения' }).selectOption('reading')
  await dialog.getByRole('checkbox', { name: 'Есть в бумажном' }).check()
  await dialog.getByRole('textbox', { name: 'Мои заметки' }).fill('Моя заметка: главное глазами не увидишь.')
  await page.reload()
  await page.getByRole('button', { name: 'Маленький принц', exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'Статус чтения' })).toHaveValue('reading')
  await expect(dialog.getByRole('checkbox', { name: 'Есть в бумажном' })).toBeChecked()
  await expect(dialog.getByRole('textbox', { name: 'Мои заметки' })).toHaveValue('Моя заметка: главное глазами не увидишь.')
  await dialog.getByText('Выбрать своё издание', { exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Книга в Яндекс Книгах' }).fill('https://books.yandex.ru/books/my-edition')
  await dialog.getByRole('button', { name: 'Сохранить издание' }).click()
  await expect(dialog.getByRole('link', { name: 'Яндекс Книги', exact: true })).toHaveAttribute('href', 'https://books.yandex.ru/books/my-edition')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Мои заметки' }).click()
  await expect(page.locator('.book-row')).toHaveCount(1)
  await page.getByText('Экспорт и исходник', { exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Резервная копия JSON' }).click()
  const backup = await downloadPromise
  const stream = await backup.createReadStream()
  let text = ''
  for await (const chunk of stream!) text += chunk.toString()
  const parsed = JSON.parse(text)
  expect(parsed.books['1'].note).toContain('Моя заметка')
  expect(Object.keys(parsed.books)).toHaveLength(118)
  await page.locator('input[type=file]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, books: { 2: { status: 'read', owned: true, note: 'Восстановлено' } }, editions: {} })) })
  await expect(page.getByRole('status')).toContainText('восстановлены')
  await expect(page.locator('.book-row')).toHaveCount(1)
  await expect(page.locator('.book-row')).toContainText('Аутсайдеры')
  await page.locator('input[type=file]').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":99,"books":{}}') })
  await expect(page.getByRole('status')).toContainText('версии 1')
  await expect(page.locator('.book-row')).toContainText('Аутсайдеры')
})

