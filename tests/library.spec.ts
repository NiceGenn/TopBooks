import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  // Core reading functionality must work even if external cover services are offline.
  await page.route(/https:\/\/(?!127\.0\.0\.1)/, route => route.abort())
  await page.goto('/')
})

test('all 118 books, hover preview, modal, source download and shop links', async ({ page }) => {
  await expect(page.getByRole('heading', { name: 'Мой список чтения.' })).toBeVisible()
  await expect(page.locator('.book-row')).toHaveCount(118)
  const title = page.getByRole('button', { name: 'Маленький принц', exact: true })
  await title.hover()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await expect(page.getByRole('tooltip').locator('.book-cover')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await title.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Маленький принц' })).toBeVisible()
  await expect(dialog.getByText('Пилот, потерпевший крушение', { exact: false })).toBeVisible()
  await expect.poll(() => dialog.locator('.book-cover img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  const yandex = new URL((await dialog.getByRole('link', { name: /Яндекс Книг/ }).getAttribute('href'))!)
  expect(yandex.hostname).toBe('books.yandex.ru')
  expect(yandex.pathname).toMatch(/^\/(books\/[^/]+|search\/all\/.+)$/)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.getByText('Экспорт и исходник', { exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Исходный Excel Оригинальный файл · 118 книг' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('Книги — дополненный список 118.xlsx')
  expect(await download.failure()).toBeNull()
})

