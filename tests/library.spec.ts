test('corrupt storage is preserved and the user is warned', async ({ page }) => {
  await page.evaluate(() => localStorage.setItem('topbooks.library.v1', 'corrupt'))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('повреждённые данные не перезаписаны')
  await expect(page.locator('.book-row')).toHaveCount(118)
  expect(await page.evaluate(() => localStorage.getItem('topbooks.library.v1'))).toBe('corrupt')
})

test('storage write failure keeps edits in memory and offers a backup', async ({ page }) => {
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Quota exceeded', 'QuotaExceededError') } })
  await page.getByRole('combobox', { name: 'Статус: Аутсайдеры', exact: true }).selectOption('reading')
  await expect(page.getByRole('alert')).toContainText('не смог сохранить')
  await expect(page.getByRole('combobox', { name: 'Статус: Аутсайдеры', exact: true })).toHaveValue('reading')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('alert').getByRole('button', { name: 'Выгрузить копию' }).click()
  expect((await downloadPromise).suggestedFilename()).toMatch(/^topbooks-.*\.json$/)
})
